-- Составной тип и домен для ФИО сотрудника
CREATE TYPE fio_type AS (
    last_name   varchar(100),
    first_name  varchar(100),
    middle_name varchar(100)
);

CREATE DOMAIN fio_valid AS fio_type
CHECK (
    (VALUE).last_name  IS NOT NULL AND length(trim((VALUE).last_name))  > 1
    AND
    (VALUE).first_name IS NOT NULL AND length(trim((VALUE).first_name)) > 1
);

-- Уровень 1. Независимые справочники
CREATE TABLE category (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
        CONSTRAINT chk_category_name CHECK (length(trim(name)) > 2),
    description text
);

CREATE TABLE unit (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
        CONSTRAINT chk_unit_name CHECK (name ~ '^[А-Яа-яЁёA-Za-z ]+$'),
    short_name varchar(5) NOT NULL UNIQUE
        CONSTRAINT chk_unit_short_name CHECK (length(trim(short_name)) BETWEEN 1 AND 5)
);

CREATE TABLE position (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
        CONSTRAINT chk_position_name CHECK (length(trim(name)) > 3)
);

CREATE TABLE payment_type (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
        CONSTRAINT chk_payment_type_name CHECK (length(trim(name)) > 3)
);

CREATE TABLE write_off_reason (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
        CONSTRAINT chk_write_off_reason_name CHECK (length(trim(name)) > 3)
);

CREATE TABLE manufacturer (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
        CONSTRAINT chk_manufacturer_name CHECK (length(trim(name)) > 2),
    country varchar(100) NOT NULL DEFAULT 'Россия'
        CONSTRAINT chk_manufacturer_country CHECK (country ~ '^[А-Яа-яЁёA-Za-z -]+$')
);

-- Уровень 3. Ключевые объекты
CREATE TABLE supplier (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
        CONSTRAINT chk_supplier_name CHECK (length(trim(name)) > 2),
    inn varchar(12) NOT NULL UNIQUE
        CONSTRAINT chk_supplier_inn CHECK (inn ~ '^[0-9]{10}([0-9]{2})?$'),
    phone varchar(20) NOT NULL
        CONSTRAINT chk_supplier_phone CHECK (phone ~ '^\+?[0-9 ()-]{6,20}$')
);

CREATE TABLE store (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    address varchar(255) NOT NULL UNIQUE
        CONSTRAINT chk_store_address CHECK (length(trim(address)) > 10),
    phone varchar(20),
    inn varchar(12)
        CONSTRAINT chk_store_inn CHECK (inn IS NULL OR inn ~ '^[0-9]{10}([0-9]{2})?$')
);

CREATE TABLE employee (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name fio_valid NOT NULL,
    login varchar(50) NOT NULL UNIQUE
        CONSTRAINT chk_employee_login CHECK (length(trim(login)) >= 5),
    password varchar(255) NOT NULL
        CONSTRAINT chk_employee_password CHECK (length(password) >= 8),
    is_active boolean NOT NULL DEFAULT true,
    position_id integer NOT NULL
);

CREATE TABLE product (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
        CONSTRAINT chk_product_name CHECK (length(trim(name)) > 3),
    barcode varchar(13) NOT NULL UNIQUE
        CONSTRAINT chk_product_barcode CHECK (barcode ~ '^([0-9]{8}|[0-9]{13})$'),
    retail_price numeric(10, 2) NOT NULL
        CONSTRAINT chk_product_retail_price CHECK (retail_price > 0),
    is_labeled boolean NOT NULL DEFAULT false,
    category_id integer NOT NULL,
    manufacturer_id integer,
    unit_id integer NOT NULL
);

-- Уровень 4. Документы и регистры
CREATE TABLE supply (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    invoice_number varchar(50) NOT NULL UNIQUE,
    supplier_id integer NOT NULL,
    employee_id integer NOT NULL
);

CREATE TABLE stock (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity integer NOT NULL DEFAULT 0
        CONSTRAINT chk_stock_quantity CHECK (quantity >= 0),
    purchase_price numeric(10, 2) NOT NULL
        CONSTRAINT chk_stock_purchase_price CHECK (purchase_price > 0),
    expiration_date date NOT NULL,
    product_id integer NOT NULL,
    store_id integer NOT NULL,
    supply_id integer NOT NULL
);

CREATE TABLE sale (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_amount numeric(10, 2) NOT NULL DEFAULT 0.00
        CONSTRAINT chk_sale_total_amount CHECK (total_amount >= 0),
    employee_id integer NOT NULL,
    store_id integer NOT NULL,
    payment_type_id integer NOT NULL
);

CREATE TABLE movement (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    employee_id integer NOT NULL
);

CREATE TABLE write_off (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    employee_id integer NOT NULL,
    write_off_reason_id integer NOT NULL
);

-- Уровень 5. Промежуточные таблицы
CREATE TABLE supply_item (
    supply_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 1
        CONSTRAINT chk_supply_item_quantity CHECK (quantity > 0),
    purchase_price numeric(10, 2) NOT NULL
        CONSTRAINT chk_supply_item_price CHECK (purchase_price > 0),
    expiration_date date NOT NULL,
    PRIMARY KEY (supply_id, product_id)
);

CREATE TABLE sale_item (
    sale_id integer NOT NULL,
    stock_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 1
        CONSTRAINT chk_sale_item_quantity CHECK (quantity > 0),
    sale_price numeric(10, 2) NOT NULL
        CONSTRAINT chk_sale_item_price CHECK (sale_price > 0),
    PRIMARY KEY (sale_id, stock_id)
);

CREATE TABLE movement_item (
    movement_id integer NOT NULL,
    stock_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 1
        CONSTRAINT chk_movement_item_quantity CHECK (quantity > 0),
    PRIMARY KEY (movement_id, stock_id)
);

CREATE TABLE write_off_item (
    write_off_id integer NOT NULL,
    stock_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 1
        CONSTRAINT chk_write_off_item_quantity CHECK (quantity > 0),
    PRIMARY KEY (write_off_id, stock_id)
);

